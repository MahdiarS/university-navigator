import { z } from "zod";
import buildingsJson from "@data/indoor/buildings.json";
import floorsJson from "@data/indoor/floors.json";
import roomsJson from "@data/indoor/rooms.json";
import departmentsJson from "@data/indoor/departments.json";
import servicesJson from "@data/indoor/department-services.json";
import entrancesJson from "@data/indoor/entrances.json";
import facilitiesJson from "@data/indoor/facilities.json";
import nodesJson from "@data/indoor/navigation-nodes.json";
import edgesJson from "@data/indoor/navigation-edges.json";
import interiorsJson from "@data/indoor/interiors.json";
import campusLayoutJson from "@data/campus/campus-layout.json";
import {
  BuildingSchema,
  CampusSchema,
  DepartmentSchema,
  DepartmentServiceSchema,
  EntranceSchema,
  FacilitySchema,
  FloorSchema,
  InteriorsSchema,
  ModelManifestSchema,
  NavEdgeSchema,
  NavNodeSchema,
  RoomSchema,
} from "./schemas";
import type { NavigatorData } from "./types";

/**
 * The 3D model manifest: the campus site plan (data/campus/campus-layout.json, extracted from the supplied CAD drawing by
 * scripts/cad/build_campus.py) and the first-floor interiors of buildings 1-3 with their sky bridges
 * (data/indoor/interiors.json, produced by scripts/cad/build_interiors.py from the owner's hand-drawn sketches).
 */
export const manifestInput: unknown = {
  schemaVersion: 1,
  note: "Campus plan from the supplied DWG; interiors of buildings 1-3 designed from the owner's sketches (not surveyed).",
  units: "meters",
  coordinateSystem: {
    x: "horizontal axis one (east +)",
    y: "vertical elevation (up +)",
    z: "horizontal axis two (south +, i.e. -Z is north in plan view)",
    origin: "south-west corner of the site-plan drawing extents (campus meters)",
  },
  campus: CampusSchema.parse(campusLayoutJson),
  interiors: InteriorsSchema.parse(interiorsJson),
};

/**
 * Local data source (data/indoor/*.json, generated by scripts/cad/build_interiors.py), validated with Zod so a
 * broken edit fails loudly at startup.
 */
export function loadDemoData(): NavigatorData {
  return {
    source: "demo",
    buildings: z.array(BuildingSchema).parse(buildingsJson),
    floors: z.array(FloorSchema).parse(floorsJson),
    rooms: z.array(RoomSchema).parse(roomsJson),
    departments: z.array(DepartmentSchema).parse(departmentsJson),
    services: z.array(DepartmentServiceSchema).parse(servicesJson),
    entrances: z.array(EntranceSchema).parse(entrancesJson),
    facilities: z.array(FacilitySchema).parse(facilitiesJson),
    nodes: z.array(NavNodeSchema).parse(nodesJson),
    edges: z.array(NavEdgeSchema).parse(edgesJson),
    manifest: ModelManifestSchema.parse(manifestInput),
  };
}
