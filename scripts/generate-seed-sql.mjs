#!/usr/bin/env node
// Builds database/seed.sql from data/indoor/*.json (the output of scripts/cad/build_interiors.py).
// Usage: node scripts/generate-seed-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (name) => JSON.parse(readFileSync(join(root, "data", "indoor", `${name}.json`), "utf8"));

const q = (v) => (v === null || v === undefined ? "null" : typeof v === "boolean" ? String(v) : typeof v === "number" ? String(v) : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;
const insert = (table, cols, rows) =>
  rows.length === 0
    ? ""
    : `insert into public.${table} (${cols.join(", ")}) values\n${rows.map((r) => `  (${r.join(", ")})`).join(",\n")}\non conflict (id) do nothing;\n\n`;

const buildings = read("buildings");
const floors = read("floors");
const nodes = read("navigation-nodes");
const rooms = read("rooms");
const departments = read("departments");
const services = read("department-services");
const entrances = read("entrances");
const edges = read("navigation-edges");
const facilities = read("facilities");

// nodes of a room's door are referenced by rooms.door_node_id, so insert nodes first
let sql = `-- Generated by scripts/generate-seed-sql.mjs from data/indoor/*.json. DO NOT EDIT BY HAND.
-- First-floor plans of buildings 1-3 as designed from hand-drawn sketches (names and numbers are low confidence, geometry is
-- not surveyed): proofread them in the admin console before relying on them.

`;
sql += insert("buildings", ["id", "name", "slug", "description", "model_url", "is_active", "is_demo"], buildings.map((b) => [q(b.id), q(b.name), q(b.slug), q(b.description), q(b.modelUrl), q(b.isActive), q(b.isDemo)]));
sql += insert("floors", ["id", "building_id", "floor_number", "display_name", "elevation", "model_url", "is_demo"], floors.map((f) => [q(f.id), q(f.buildingId), q(f.floorNumber), q(f.displayName), q(f.elevation), q(f.modelUrl), q(f.isDemo)]));
sql += insert("navigation_nodes", ["id", "floor_id", "node_type", "position_x", "position_y", "position_z", "label", "is_demo"], nodes.map((n) => [q(n.id), q(n.floorId), q(n.type), q(n.x), q(n.y), q(n.z), q(n.label), q(n.isDemo)]));
sql += insert("rooms", ["id", "floor_id", "room_number", "name", "room_type", "model_object_id", "position_x", "position_y", "position_z", "door_node_id", "is_demo"], rooms.map((r) => [q(r.id), q(r.floorId), q(r.roomNumber), q(r.name), q(r.roomType), q(r.modelObjectId), q(r.positionX), q(r.positionY), q(r.positionZ), q(r.doorNodeId), q(r.isDemo)]));
sql += insert("departments", ["id", "room_id", "name", "slug", "description", "phone", "working_hours", "keywords", "is_active", "is_demo"], departments.map((d) => [q(d.id), q(d.roomId), q(d.name), q(d.slug), q(d.description), q(d.phone), q(d.workingHours), arr(d.keywords), q(d.isActive), q(d.isDemo)]));
sql += insert("department_services", ["id", "department_id", "service_name", "keywords", "is_demo"], services.map((s) => [q(s.id), q(s.departmentId), q(s.serviceName), arr(s.keywords), q(s.isDemo)]));
sql += insert("entrances", ["id", "building_id", "floor_id", "name", "position_x", "position_y", "position_z", "node_id", "is_demo"], entrances.map((e) => [q(e.id), q(e.buildingId), q(e.floorId), q(e.name), q(e.positionX), q(e.positionY), q(e.positionZ), q(e.nodeId), q(e.isDemo)]));
sql += insert("navigation_edges", ["id", "from_node_id", "to_node_id", "distance", "edge_type", "accessible", "bidirectional", "is_demo"], edges.map((e) => [q(e.id), q(e.fromNode), q(e.toNode), q(e.distance), q(e.edgeType), q(e.accessible), q(e.bidirectional), q(e.isDemo)]));
sql += insert("facilities", ["id", "floor_id", "facility_type", "name", "position_x", "position_y", "position_z", "is_demo"], facilities.map((f) => [q(f.id), q(f.floorId), q(f.facilityType), q(f.name), q(f.positionX), q(f.positionY), q(f.positionZ), q(f.isDemo)]));

writeFileSync(join(root, "database", "seed.sql"), sql);
console.log(`database/seed.sql: ${buildings.length} buildings, ${floors.length} floors, ${nodes.length} nodes, ${rooms.length} rooms, ${departments.length} departments, ${edges.length} edges`);
